package oop.interfaces;

/**
 * A Marker Interface is like a VIP badge!
 * 
 * It has NO rules (no methods) and NO information (no fields).
 * It is completely empty!
 * 
 * Why do we use it? 
 * It's just a way to tag a class. If a class wears this "VIP badge" (implements it),
 * Java knows this class is special and should be treated differently.
 * (Like telling the Java security guard: "Hey, let this class through!")
 */
public interface MarkerInterface {

    // Look! Nothing here! 
    // It's just an empty badge.
}